#!/bin/sh
# Writes the fork's commits since ghostty-ref back to mods/ghostty/,
# replacing the patches there, without the generated branding commit
# (scripts/brand.py). Each patch's .md is pointed at its new file name by
# subject (scripts/mods.py relink); a new patch, or one whose subject
# changed, needs its .md written or fixed by hand, and the check at the end
# names it. Run after every change to the fork.
#
#   scripts/export.sh
set -eu
HERE="$(cd "$(dirname "$0")/.." && pwd)"
FORK="${HOTTYTERM_GHOSTTY:-$(dirname "$HERE")/ghostty}"
SET="$HERE/mods/ghostty"
REV="$(grep -v '^#' "$HERE/ghostty-ref" | head -1)"
BRAND="hottyterm: branding (generated by scripts/brand.py)"
TOP=hottyterm
[ "$(git -C "$FORK" log -1 --format=%s "$TOP")" = "$BRAND" ] && TOP="hottyterm~1"
if git -C "$FORK" log --format=%s "$REV..$TOP" | grep -qxF "$BRAND"; then
  echo "commits sit on top of the branding: run scripts/brand.py first (it moves the branding to the top)" >&2
  exit 1
fi
NEW="$(mktemp -d)"; trap 'rm -rf "$NEW"' EXIT
git -C "$FORK" format-patch -q --no-signature --zero-commit -o "$NEW" "$REV..$TOP"
python3 "$HERE/scripts/mods.py" relink "$SET" "$NEW" || true
rm -f "$SET"/*.patch
mv "$NEW"/*.patch "$SET"/
ls "$SET"/*.patch | sed "s|^$SET/||"
python3 "$HERE/scripts/mods.py" check "$HERE"
